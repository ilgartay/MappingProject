/**
 * Seçilen bölgelerden WKT üretir.
 *
 * Tek parça POLYGON, birden çoğu MULTIPOLYGON döner. Bölgeler birbirinin
 * üstüne binmiyor, sadece yan yana duruyor; MULTIPOLYGON tam olarak bunu
 * ifade ediyor ve tarayıcıya geometri kütüphanesi eklemek gerekmiyor.
 *
 * Yan yana iki bölge ortak kenar paylaştığı için ortaya çıkan MULTIPOLYGON
 * OGC kurallarına göre geçersizdir; sunucu kaydetmeden önce parçaları
 * birleştiriyor (WktParser.ParseArea).
 *
 * @param {string[]} ids seçili bölge kimlikleri
 * @returns {string|null} boş seçimde null
 */
export function regionsToWkt(ids) {
  const parts = TURKEY_REGIONS
    .filter((region) => ids.includes(region.id))
    .flatMap((region) => region.parts)

  if (parts.length === 0) return null
  if (parts.length === 1) return `POLYGON ${parts[0]}`

  return `MULTIPOLYGON (${parts.join(', ')})`
}
